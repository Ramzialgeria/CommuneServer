using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace CommuneServer.Activation
{
    public class ActivationPackage
    {
        public int ActivationVersion { get; set; }

        public string ActivationType { get; set; }

        public string ActivationId { get; set; }

        // Must match <add key="ServerCode"> of this installation
        public string ServerCode { get; set; }

        // APW
        public ActivationWilaya Wilaya { get; set; }

        public List<ActivationCommune> Communes { get; set; } = new List<ActivationCommune>(); 
        
        // APC
        public ActivationCommune Commune { get; set; } 
        
        // Common
        public List<ActivationListe> Listes { get; set; } = new List<ActivationListe>();

        public List<ActivationUser> Users { get; set; } = new List<ActivationUser>();
    }

    public class ActivationWilaya
    {
        public string CodeWilaya { get; set; }

        public string NameWilaya { get; set; }

        public List<ActivationCommune> Communes { get; set; }
           = new List<ActivationCommune>();
    }

    public class ActivationCommune
    {
        public string CodeCommune { get; set; }

        public string NameCommune { get; set; }

        public string CodeWilaya { get; set; }

        public List<ActivationCentre> Centres { get; set; }
           = new List<ActivationCentre>();
    }

    public class ActivationCentre
    {
        public long Id { get; set; }
        public string Code { get; set; }
        public string Lib { get; set; }
        public string Type { get; set; }
        public int NbInscrit { get; set; }
        public List<ActivationBureau> Bureaux { get; set; }
    }

    public class ActivationBureau
    {
        public long Id { get; set; }
        public string Code { get; set; }
        public string Type { get; set; }
        public int NbInscrit { get; set; }
    }

    public class ActivationListe
    {
        public long Id { get; set; }
        public string Lib { get; set; }
        public int NumIdentifiant { get; set; }
        public List<ActivationCandidat> Candidats { get; set; }
    }

    public class ActivationCandidat
    {
        public long Id { get; set; }

        public string FullNameAr { get; set; }

        public string FullNameFr { get; set; }

        public int? Ordre { get; set; }
    }

    public class ActivationUser
    {
        public string Id { get; set; }
        public string UserName { get; set; }

        //public string Password { get; set; }
        
        // BCrypt hash, generated by central (no clear password in the file)
        public string PasswordHash { get; set; }

        public string Role { get; set; }

        public string CodeStructure { get; set; }
    }
}
